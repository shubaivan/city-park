    public function __invoke(Nutgram $bot): void
    {
        $data = $bot->isCallbackQuery() ? ($bot->callbackQuery()->data ?? '') : '';

        if (str_starts_with($data, 'info-topic:')) {
            $key = substr($data, strlen('info-topic:'));
            $this->renderTopic($bot, $key);
            return;
        }

        $this->renderMenu($bot, $data === self::MENU_CALLBACK);
    }

    /**
     * Topics that answer half of the same question each.
     *
     * The announcement links straight to «🪪 QR-код мешканця», and a reader arriving there
     * had no way of learning that passes for builders exist at all — «⬅️ До списку тем»
     * asks them to go back and guess. One tap instead.
     */
    private const RELATED = [
        'qr' => ['passes', '👷 Пропуски для робітників'],
        'passes' => ['qr', '🪪 QR-код мешканця'],
    ];

    /**
     * Somebody followed a link from the residents' chat straight to one topic.
     *
     * A forwarded link may arrive months later, from a post about a topic that has since
     * been renamed away — an unknown id opens the list rather than erroring, the same call
     * `StartPayloadCommand` makes for an unknown payload.
     */
    public function openFromDeepLink(Nutgram $bot, int $id): void
    {
        $key = array_search($id, self::LINKABLE, true);

        $key === false
            ? $this->renderMenu($bot, false)
            : $this->renderTopic($bot, (string)$key);
    }

    private function renderMenu(Nutgram $bot, bool $edit): void
    {
        $text = "ℹ️ <b>Інструкція та FAQ</b>\n\nОберіть тему, щоб дізнатися більше:";

        $markup = InlineKeyboardMarkup::make();
        foreach (self::TOPICS as $key => $topic) {
            $markup->addRow(
                InlineKeyboardButton::make($topic['title'], callback_data: 'info-topic:' . $key)
            );
        }
        $markup->addRow(StartCommand::homeButton());

        if ($edit) {
            try {
                $bot->editMessageText(text: $text, parse_mode: ParseMode::HTML, reply_markup: $markup);
                return;
            } catch (\Throwable) {
                // fall through to a fresh message
            }
        }

        $bot->sendMessage(text: $text, parse_mode: ParseMode::HTML, reply_markup: $markup);
    }

    private function renderTopic(Nutgram $bot, string $key): void
    {
        $topic = self::TOPICS[$key] ?? null;
        if (!$topic) {
            $this->renderMenu($bot, true);
            return;
        }

        $markup = InlineKeyboardMarkup::make();

        if (isset(self::RELATED[$key])) {
            [$related, $label] = self::RELATED[$key];
            $markup->addRow(InlineKeyboardButton::make($label, callback_data: 'info-topic:' . $related));
        }

        $markup
            ->addRow(
                InlineKeyboardButton::make('⬅️ До списку тем', callback_data: self::MENU_CALLBACK)
            )
            ->addRow(StartCommand::homeButton());

        // Edited in place when the reader is walking the menu; sent fresh when they
        // arrived from a link, where there is no message of ours to edit.
        try {
            $bot->isCallbackQuery()
                ? $bot->editMessageText(text: $topic['body'], parse_mode: ParseMode::HTML, reply_markup: $markup)
                : $bot->sendMessage(text: $topic['body'], parse_mode: ParseMode::HTML, reply_markup: $markup);
        } catch (\Throwable) {
            $bot->sendMessage(text: $topic['body'], parse_mode: ParseMode::HTML, reply_markup: $markup);
        }
    }
